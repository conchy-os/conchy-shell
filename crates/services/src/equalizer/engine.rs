/// The virtual sink every stream is sent to while the equalizer is on.
pub const SINK_NAME: &str = "conchy_eq_sink";
const OUTPUT_STREAM_NAME: &str = "conchy_eq_out";

const KEY_CONFIGURED: &str = "default.configured.audio.sink";
const KEY_ACTUAL: &str = "default.audio.sink";

/// How long a chain gets to show its sink before the attempt counts as
/// failed.
const START_TIMEOUT: Duration = Duration::from_secs(10);
/// A slider drag is one write to disk, this long after its last move.
const SAVE_DELAY: Duration = Duration::from_millis(400);
const POLL: Duration = Duration::from_millis(500);

/// What the loop thread is told.
pub enum Wake {
    /// Commands are waiting in the job queue.
    Jobs,
    /// Time to look at the chain and the unsaved settings.
    Tick,
    /// The service stopped.
    Quit,
}

// -- the chain's config -------------------------------------------------------

/// The `pipewire -c` file for a chain that plays to `output`, with the
/// controls at the values of `settings`.
pub fn chain_config(output: &str, settings: &Settings) -> String {
    let mut nodes = format!(
        "          {{ type = builtin name = preamp label = linear control = {{ Mult = {:.6} Add = 0.0 }} }}\n",
        db_to_mult(settings.effective_preamp_db())
    );
    let mut links = String::new();
    let mut previous = "preamp".to_string();
    for band in 0..BAND_COUNT {
        let name = format!("band_{band}");
        nodes.push_str(&format!(
            "          {{ type = builtin name = {name} label = {} control = {{ Freq = {:.2} Q = {:.2} Gain = {:.1} }} }}\n",
            dsp::shape(band).label(),
            dsp::FREQUENCIES[band],
            dsp::q(band),
            settings.curve.gains[band],
        ));
        links.push_str(&format!(
            "          {{ output = \"{previous}:Out\" input = \"{name}:In\" }}\n"
        ));
        previous = name;
    }

    format!(
        r#"# Generated by the shell's equalizer; rewritten every time the chain starts.
context.properties = {{
    log.level = 1
}}
context.spa-libs = {{
    audio.convert.* = audioconvert/libspa-audioconvert
    support.*       = support/libspa-support
}}
context.modules = [
    {{ name = libpipewire-module-rt args = {{ }} flags = [ ifexists nofail ] }}
    {{ name = libpipewire-module-protocol-native }}
    {{ name = libpipewire-module-client-node }}
    {{ name = libpipewire-module-adapter }}
    {{ name = libpipewire-module-filter-chain
        args = {{
            node.description = "Conchy Equalizer"
            media.name = "Conchy Equalizer"
            filter.graph = {{
                nodes = [
{nodes}                ]
                links = [
{links}                ]
            }}
            audio.channels = 2
            audio.position = [ FL FR ]
            capture.props = {{
                node.name = "{SINK_NAME}"
                media.class = Audio/Sink
            }}
            playback.props = {{
                node.name = "{OUTPUT_STREAM_NAME}"
                node.passive = true
                target.object = {target}
            }}
        }}
    }}
]
"#,
        target = quoted(output),
    )
}

fn db_to_mult(db: f32) -> f32 {
    10f32.powf(db / 20.0)
}

/// The live controls of the chain, as the pairs a `Props` update carries.
fn controls(settings: &Settings) -> Vec<(String, f32)> {
    let mut controls = vec![(
        "preamp:Mult".to_string(),
        db_to_mult(settings.effective_preamp_db()),
    )];
    for (band, gain) in settings.curve.gains.iter().enumerate() {
        controls.push((format!("band_{band}:Gain"), *gain));
    }
    controls
}

// -- the engine ---------------------------------------------------------------

struct Sink {
    name: String,
    description: String,
}

struct Chain {
    child: Child,
    output: String,
    started: Instant,
}

struct State {
    settings: Settings,
    engine: EngineState,
    /// Every real sink, by registry id.
    sinks: BTreeMap<u32, Sink>,
    eq_id: Option<u32>,
    eq_node: Option<Node>,
    /// The chain's controls were sent since the node appeared.
    params_sent: bool,
    metadata: Option<Metadata>,
    configured: Option<String>,
    actual: Option<String>,
    /// What the user last set as the default sink, the equalizer aside; what
    /// turning it off puts back (`None`: the key was never set).
    user_configured: Option<String>,
    /// The sink the equalized sound goes to.
    system_output: Option<String>,
    chain: Option<Chain>,
    dirty_since: Option<Instant>,
    /// When the default was last pointed at the equalizer, so a slow
    /// metadata round trip is not answered with a second write.
    default_set_at: Option<Instant>,
    failure: Option<String>,
}

pub struct Engine {
    data: Mutable<EqualizerData>,
    token: RunToken,
    wake: pipewire::channel::Sender<Wake>,
    state: RefCell<State>,
    tick_pending: Cell<bool>,
    /// Proxies and their listeners, alive as long as the engine.
    keep: RefCell<Vec<Box<dyn Listener>>>,
}

impl Engine {
    pub fn new(
        data: Mutable<EqualizerData>,
        token: RunToken,
        wake: pipewire::channel::Sender<Wake>,
        settings: Settings,
    ) -> Rc<Self> {
        Rc::new(Self {
            data,
            token,
            wake,
            state: RefCell::new(State {
                settings,
                engine: EngineState::Off,
                sinks: BTreeMap::new(),
                eq_id: None,
                eq_node: None,
                params_sent: false,
                metadata: None,
                configured: None,
                actual: None,
                user_configured: None,
                system_output: None,
                chain: None,
                dirty_since: None,
                default_set_at: None,
                failure: None,
            }),
            tick_pending: Cell::new(false),
            keep: RefCell::new(Vec::new()),
        })
    }

    /// The error that ended the run, if one did.
    pub fn take_failure(&self) -> Option<String> {
        self.state.borrow_mut().failure.take()
    }

    // -- events ---------------------------------------------------------------

    pub fn on_global(
        self: &Rc<Self>,
        registry: &pipewire::registry::RegistryRc,
        global: &pipewire::registry::GlobalObject<&pipewire::spa::utils::dict::DictRef>,
    ) {
        match global.type_ {
            ObjectType::Node => {
                let Some(props) = global.props else { return };
                if props.get("media.class") != Some("Audio/Sink") {
                    return;
                }
                let name = props.get("node.name").unwrap_or_default().to_string();
                if name == SINK_NAME {
                    match registry.bind::<Node, _>(global) {
                        Ok(node) => {
                            debug!("Equalizer sink is up (node {})", global.id);
                            let mut state = self.state.borrow_mut();
                            state.eq_id = Some(global.id);
                            state.eq_node = Some(node);
                            state.params_sent = false;
                        }
                        Err(err) => warn!("Binding the equalizer sink: {err}"),
                    }
                } else {
                    let description = props
                        .get("node.description")
                        .or_else(|| props.get("node.nick"))
                        .unwrap_or(&name)
                        .to_string();
                    self.state
                        .borrow_mut()
                        .sinks
                        .insert(global.id, Sink { name, description });
                }
            }
            ObjectType::Metadata => {
                let Some(props) = global.props else { return };
                if props.get("metadata.name") != Some("default") {
                    return;
                }
                match registry.bind::<Metadata, _>(global) {
                    Ok(metadata) => {
                        let engine = Rc::downgrade(self);
                        let listener = metadata
                            .add_listener_local()
                            .property(move |subject, key, _type, value| {
                                if subject == 0
                                    && let Some(engine) = engine.upgrade()
                                {
                                    engine.on_metadata(key, value);
                                }
                                0
                            })
                            .register();
                        self.state.borrow_mut().metadata = Some(metadata);
                        self.keep.borrow_mut().push(Box::new(listener));
                    }
                    Err(err) => warn!("Binding the default metadata: {err}"),
                }
            }
            _ => return,
        }
        self.reconcile();
    }

    pub fn on_global_remove(&self, id: u32) {
        {
            let mut state = self.state.borrow_mut();
            state.sinks.remove(&id);
            if state.eq_id == Some(id) {
                state.eq_id = None;
                state.eq_node = None;
                state.params_sent = false;
            }
        }
        self.reconcile();
    }

    fn on_metadata(&self, key: Option<&str>, value: Option<&str>) {
        {
            let mut state = self.state.borrow_mut();
            match key {
                Some(KEY_CONFIGURED) => {
                    let name = default_sink_name(value);
                    if name.as_deref() != Some(SINK_NAME) {
                        state.user_configured.clone_from(&name);
                    }
                    state.configured = name;
                }
                Some(KEY_ACTUAL) => state.actual = default_sink_name(value),
                _ => return,
            }
        }
        self.reconcile();
    }

    pub fn on_wake(&self, jobs: &Mutex<JobReceiver<EqualizerCommand>>) {
        jobs.lock()
            .unwrap_or_else(PoisonError::into_inner)
            .drain(|command| {
                self.apply(command);
                Ok(())
            });
    }

    pub fn on_tick(&self) {
        self.tick_pending.set(false);

        let flush = {
            let state = self.state.borrow();
            state
                .dirty_since
                .is_some_and(|since| since.elapsed() >= SAVE_DELAY)
        };
        if flush {
            self.save();
        }

        let problem = {
            let mut state = self.state.borrow_mut();
            let starting = state.eq_node.is_none();
            state.chain.as_mut().and_then(|chain| match chain.child.try_wait() {
                Ok(Some(status)) => Some(format!("the filter-chain exited ({status})")),
                Ok(None) if starting && chain.started.elapsed() > START_TIMEOUT => {
                    Some("the filter-chain did not come up (see $XDG_RUNTIME_DIR/conchy/eq-chain.log)".to_string())
                }
                Ok(None) => None,
                Err(err) => Some(format!("watching the filter-chain: {err}")),
            })
        };
        if let Some(problem) = problem {
            self.fail(problem);
            return;
        }
        self.schedule_tick();
    }

    // -- commands -------------------------------------------------------------

    fn apply(&self, command: EqualizerCommand) {
        use EqualizerCommand as C;
        let mut changed_curve = false;
        {
            let mut guard = self.state.borrow_mut();
            let state = &mut *guard;
            let settings = &mut state.settings;
            match command {
                C::SetEnabled(on) => settings.enabled = on,
                C::SetBand { band, gain } => {
                    settings.set_band(band, gain);
                    changed_curve = true;
                }
                C::SetPreamp(db) => {
                    settings.set_preamp(db);
                    changed_curve = true;
                }
                C::SetAutoPreamp(on) => {
                    settings.auto_preamp = on;
                    changed_curve = true;
                }
                C::ApplyPreset(name) => {
                    if settings.apply_preset(&name) {
                        changed_curve = true;
                    } else {
                        warn!("No equalizer preset called {name:?}");
                    }
                }
                C::Reset => {
                    settings.curve = model::Curve::default();
                    changed_curve = true;
                }
                C::SavePreset(name) => {
                    if let Err(err) = settings.save_preset(&name) {
                        warn!("Saving the preset: {err:#}");
                    }
                }
                C::DeletePreset(name) => {
                    settings.delete_preset(&name);
                }
                C::SetOutput(name) => {
                    // Picking an output is picking the system default; the
                    // chain follows it like it follows anyone else's pick.
                    let metadata = state.metadata.as_ref();
                    match metadata {
                        Some(metadata) => set_default(metadata, &name),
                        None => warn!("No metadata to set the output through"),
                    }
                    return;
                }
            }
            state.dirty_since = Some(Instant::now());
        }
        if changed_curve {
            self.push_params();
        }
        self.reconcile();
        self.schedule_tick();
    }

    // -- the chain ------------------------------------------------------------

    /// Bring the chain, the default sink and the published state in line
    /// with the settings.
    fn reconcile(&self) {
        self.refresh_system_output();

        let (enabled, output, running_output) = {
            let state = self.state.borrow();
            let output = state
                .system_output
                .clone()
                .filter(|name| state.sinks.values().any(|sink| &sink.name == name));
            (
                state.settings.enabled,
                output,
                state.chain.as_ref().map(|chain| chain.output.clone()),
            )
        };

        if !enabled {
            if running_output.is_some() {
                self.stop_chain();
            }
            self.set_engine(EngineState::Off);
            return;
        }

        let Some(output) = output else {
            if running_output.is_some() {
                self.stop_chain();
            }
            self.set_engine(EngineState::Starting);
            return;
        };

        if running_output
            .as_ref()
            .is_some_and(|current| *current != output)
        {
            info!("Output changed to {output}, rebuilding the equalizer chain");
            self.stop_chain();
        }
        if self.state.borrow().chain.is_none()
            && let Err(err) = self.start_chain(&output)
        {
            self.fail(format!("{err:#}"));
            return;
        }

        let ready = self.state.borrow().eq_node.is_some();
        if ready {
            if !self.state.borrow().params_sent {
                self.push_params();
            }
            self.point_default_at_the_equalizer();
            self.set_engine(EngineState::Running);
        } else {
            self.set_engine(EngineState::Starting);
        }
    }

    /// The real sink the sound should reach: what the system names as its
    /// default, unless that is the equalizer itself.
    fn refresh_system_output(&self) {
        let mut state = self.state.borrow_mut();
        let candidates = [state.configured.clone(), state.actual.clone()];
        let real = |name: &String| name != SINK_NAME;
        let known = |name: &String| state.sinks.values().any(|sink| &sink.name == name);
        let pick = candidates
            .iter()
            .flatten()
            .filter(|name| real(name))
            .find(|name| known(name))
            .or_else(|| candidates.iter().flatten().find(|name| real(name)))
            .cloned();
        if let Some(pick) = pick {
            state.system_output = Some(pick);
        }
    }

    fn start_chain(&self, output: &str) -> anyhow::Result<()> {
        let conf = runtime_file("eq-chain.conf");
        let log = runtime_file("eq-chain.log");
        if let Some(dir) = conf.parent() {
            std::fs::create_dir_all(dir).context("creating the runtime directory")?;
        }
        std::fs::write(&conf, chain_config(output, &self.state.borrow().settings))
            .context("writing the filter-chain config")?;
        let child = pwutil::spawn_chain(&conf, &log)?;
        info!("Equalizer chain started for {output} (pid {})", child.id());

        let mut state = self.state.borrow_mut();
        state.chain = Some(Chain {
            child,
            output: output.to_string(),
            started: Instant::now(),
        });
        state.eq_id = None;
        state.eq_node = None;
        state.params_sent = false;
        drop(state);
        self.schedule_tick();
        Ok(())
    }

    /// Stop the chain. When the default still points at the equalizer, give
    /// it back to the real sink first.
    fn stop_chain(&self) {
        let mut state = self.state.borrow_mut();
        if state.configured.as_deref() == Some(SINK_NAME)
            && let Some(metadata) = &state.metadata
        {
            match &state.user_configured {
                Some(name) => set_default(metadata, name),
                None => metadata.set_property(0, KEY_CONFIGURED, None, None),
            }
        }
        if let Some(mut chain) = state.chain.take() {
            let _ = chain.child.kill();
            let _ = chain.child.wait();
            info!("Equalizer chain stopped");
        }
        state.eq_node = None;
        state.eq_id = None;
        state.params_sent = false;
        state.default_set_at = None;
    }

    /// Whatever is playing follows the default sink; make that the
    /// equalizer.
    fn point_default_at_the_equalizer(&self) {
        let mut state = self.state.borrow_mut();
        if state.configured.as_deref() == Some(SINK_NAME) {
            return;
        }
        if state
            .default_set_at
            .is_some_and(|at| at.elapsed() < Duration::from_secs(1))
        {
            return;
        }
        if let Some(metadata) = &state.metadata {
            set_default(metadata, SINK_NAME);
            state.default_set_at = Some(Instant::now());
        }
    }

    fn push_params(&self) {
        let mut state = self.state.borrow_mut();
        let Some(node) = &state.eq_node else { return };
        let Some(bytes) = params_pod(&controls(&state.settings)) else {
            warn!("Could not build the equalizer controls");
            return;
        };
        let Some(pod) = Pod::from_bytes(&bytes) else {
            return;
        };
        node.set_param(ParamType::Props, 0, pod);
        state.params_sent = true;
        drop(state);
        self.publish();
    }

    // -- bookkeeping ----------------------------------------------------------

    fn set_engine(&self, engine: EngineState) {
        {
            let mut state = self.state.borrow_mut();
            if state.engine == engine {
                drop(state);
                self.publish();
                return;
            }
            state.engine = engine;
        }
        self.publish();
    }

    fn fail(&self, message: String) {
        warn!("Equalizer: {message}");
        {
            let mut state = self.state.borrow_mut();
            state.engine = EngineState::Failed(message.clone());
            state.failure = Some(message);
        }
        self.publish();
        let _ = self.wake.send(Wake::Quit);
    }

    fn publish(&self) {
        let snapshot = {
            let state = self.state.borrow();
            let mut outputs: Vec<OutputDevice> = state
                .sinks
                .values()
                .map(|sink| OutputDevice {
                    name: sink.name.clone(),
                    description: sink.description.clone(),
                })
                .collect();
            outputs.sort_by(|a, b| a.description.cmp(&b.description));
            EqualizerData {
                settings: state.settings.clone(),
                engine: state.engine.clone(),
                outputs,
                output: state.system_output.clone(),
            }
        };
        self.token.write(&self.data, |data| {
            if *data != snapshot {
                *data = snapshot;
            }
        });
    }

    fn save(&self) {
        let settings = {
            let mut state = self.state.borrow_mut();
            state.dirty_since = None;
            state.settings.clone()
        };
        if let Err(err) = model::save(&settings) {
            warn!("Saving the equalizer settings: {err:#}");
        }
    }

    fn schedule_tick(&self) {
        let needed = {
            let state = self.state.borrow();
            state.chain.is_some() || state.dirty_since.is_some()
        };
        if !needed || self.tick_pending.replace(true) {
            return;
        }
        let wake = self.wake.clone();
        tokio::spawn(async move {
            tokio::time::sleep(POLL).await;
            let _ = wake.send(Wake::Tick);
        });
    }

    /// The run is over: write what is unsaved and stop the chain. Nothing is
    /// sent to the daemon any more, so the default is left to WirePlumber's
    /// fallback.
    pub fn shutdown(&self) {
        if self.state.borrow().dirty_since.is_some() {
            self.save();
        }
        let mut state = self.state.borrow_mut();
        if let Some(mut chain) = state.chain.take() {
            let _ = chain.child.kill();
            let _ = chain.child.wait();
        }
    }
}

fn set_default(metadata: &Metadata, sink: &str) {
    pwutil::set_default(metadata, KEY_CONFIGURED, sink);
}

/// One PipeWire session: connect, follow the graph, serve commands until
/// the token is superseded or the chain fails.
pub fn run(
    data: &Mutable<EqualizerData>,
    token: &RunToken,
    jobs: &Arc<Mutex<JobReceiver<EqualizerCommand>>>,
    sender_slot: &std::sync::Mutex<Option<pipewire::channel::Sender<Wake>>>,
) -> anyhow::Result<()> {
    let settings = match model::load() {
        Ok(settings) => settings,
        Err(err) => {
            warn!("Equalizer settings are unreadable, starting flat: {err:#}");
            if let Ok(path) = model::path() {
                let _ = std::fs::copy(&path, path.with_extension("kdl.bak"));
            }
            Settings::default()
        }
    };

    let mainloop = MainLoopRc::new(None)?;
    let (wake_tx, wake_rx) = pipewire::channel::channel::<Wake>();
    *sender_slot
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner) = Some(wake_tx.clone());

    let engine = Engine::new(data.clone(), token.clone(), wake_tx.clone(), settings);
    engine.publish();

    // Dropped when this attempt returns, which retires the canceller.
    let (_attempt, attempt_done) = tokio::sync::oneshot::channel::<()>();
    tokio::spawn({
        let token = token.clone();
        let wake = wake_tx.clone();
        async move {
            tokio::select! {
                _ = token.cancelled() => { let _ = wake.send(Wake::Quit); }
                _ = attempt_done => {}
            }
        }
    });

    let jobs = jobs.clone();
    let _wake = wake_rx.attach(mainloop.loop_(), {
        let mainloop = mainloop.clone();
        let engine = engine.clone();
        let jobs = jobs.clone();
        move |wake| match wake {
            Wake::Jobs => engine.on_wake(&jobs),
            Wake::Tick => engine.on_tick(),
            Wake::Quit => mainloop.quit(),
        }
    });

    let context = ContextRc::new(&mainloop, None)?;
    let core = context.connect_rc(None)?;
    let core_failure = Rc::new(RefCell::new(None::<String>));
    let _core_listener = core
        .add_listener_local()
        .error({
            let failure = core_failure.clone();
            let mainloop = mainloop.clone();
            move |id, _seq, res, message| {
                if id == pipewire::core::PW_ID_CORE {
                    *failure.borrow_mut() = Some(format!("{message} ({res})"));
                    mainloop.quit();
                }
            }
        })
        .register();

    let registry = core.get_registry_rc()?;
    let registry_weak = registry.downgrade();
    let _registry_listener = registry
        .add_listener_local()
        .global({
            let engine = engine.clone();
            move |global| {
                if let Some(registry) = registry_weak.upgrade() {
                    engine.on_global(&registry, global);
                }
            }
        })
        .global_remove({
            let engine = engine.clone();
            move |id| engine.on_global_remove(id)
        })
        .register();

    // Commands queued before this attempt had a channel to wake.
    let _ = wake_tx.send(Wake::Jobs);
    token.active();
    mainloop.run();

    engine.shutdown();
    *sender_slot
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner) = None;

    if let Some(failure) = engine.take_failure() {
        return Err(anyhow!(failure));
    }
    if let Some(failure) = core_failure.borrow_mut().take() {
        return Err(anyhow!("PipeWire connection lost: {failure}"));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_chain_config_has_a_preamp_ten_bands_and_the_target() {
        let mut settings = Settings::default();
        settings.set_band(0, 4.0);
        let text = chain_config("alsa_output.pci-0000_00_1b.0.analog-stereo", &settings);

        assert!(text.contains("label = linear"));
        assert!(text.contains("label = bq_lowshelf"));
        assert!(text.contains("label = bq_highshelf"));
        assert_eq!(text.matches("label = bq_peaking").count(), BAND_COUNT - 2);
        assert_eq!(text.matches("input = \"band_").count(), BAND_COUNT);
        assert!(text.contains("output = \"preamp:Out\" input = \"band_0:In\""));
        assert!(text.contains("output = \"band_8:Out\" input = \"band_9:In\""));
        assert!(text.contains("node.name = \"conchy_eq_sink\""));
        assert!(text.contains("media.class = Audio/Sink"));
        assert!(text.contains("target.object = \"alsa_output.pci-0000_00_1b.0.analog-stereo\""));
        // The first band starts at its gain, so there is no jump when the
        // live update arrives.
        assert!(text.contains(
            "name = band_0 label = bq_lowshelf control = { Freq = 31.25 Q = 0.80 Gain = 4.0 }"
        ));
    }

    #[test]
    fn an_odd_device_name_cannot_break_out_of_the_config() {
        let text = chain_config("a\"b\\c", &Settings::default());
        assert!(text.contains(r#"target.object = "a\"b\\c""#));
    }

    #[test]
    fn controls_follow_the_settings() {
        let mut settings = Settings::default();
        settings.set_band(3, -2.5);
        settings.auto_preamp = false;
        settings.set_preamp(-6.0);
        let controls = controls(&settings);
        assert_eq!(controls.len(), BAND_COUNT + 1);
        assert_eq!(controls[0].0, "preamp:Mult");
        assert!((controls[0].1 - 0.501).abs() < 0.01);
        assert_eq!(controls[4], ("band_3:Gain".to_string(), -2.5));
    }
}

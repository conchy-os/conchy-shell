//! The audio path of the equalizer, on PipeWire.
//!
//! Turning the equalizer on does three things:
//!
//! 1. starts a PipeWire *filter-chain* (a child `pipewire -c <file>`) that
//!    publishes a virtual sink, `conchy_eq_sink`, runs what it receives
//!    through a preamp and ten biquads, and plays the result to the real
//!    output;
//! 2. makes that sink the default, so every stream follows it;
//! 3. keeps the gains live: a slider move is one `Props` update on the
//!    sink's node, no restart and no click.
//!
//! The "real output" is whatever the system's default sink was; when it
//! changes (the user picks another device anywhere), the chain is rebuilt
//! for the new one. Turning the equalizer off stops the chain and puts the
//! default back. The child dies with the shell (`PDEATHSIG`), and
//! WirePlumber falls back to a real sink when the virtual one vanishes, so a
//! crash never leaves the machine without sound.

